import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {addWorkdays,deadlineAlert} from './work-calendar.js';
import {initCrmMail,processCrmMail} from './crm-mail.js';
test('working days skip weekends, Russian holidays and transfers; unknown calendar fails explicitly',()=>{
 assert.equal(addWorkdays('2026-11-20',5),'2026-11-27');
 assert.equal(addWorkdays('2026-12-30',1),'2027-01-11');
 assert.equal(addWorkdays('2027-02-19',1),'2027-02-20');
 assert.equal(addWorkdays('2027-02-20',1),'2027-02-24');
 assert.equal(addWorkdays('2026-05-08',1),'2026-05-12');
 assert.equal(addWorkdays('2026-11-30',-3),'2026-11-25');
 assert.throws(()=>addWorkdays('2027-12-30',1),/2028/);
 assert.throws(()=>addWorkdays('2026-02-30',1));
 const d={stage:'work',deadline:'2026-11-30'};
 assert.equal(deadlineAlert(d,'2026-11-24'),null);assert.equal(deadlineAlert(d,'2026-11-25').kind,'soon');
 assert.equal(deadlineAlert(d,'2026-11-30').kind,'today');assert.equal(deadlineAlert(d,'2026-12-01').kind,'overdue');
 for(const stage of ['new','won','lost','act_ready','act_sent'])assert.equal(deadlineAlert({...d,stage},'2026-11-25'),null);
 assert.equal(deadlineAlert({...d,deleted_at:'yes'},'2026-11-25'),null);
});
test('mail goes only to responsible, deduplicates, retries failure and stops on completion',async()=>{
 const db=new DatabaseSync(':memory:');
 db.exec(`CREATE TABLE users(id TEXT,email TEXT);INSERT INTO users VALUES('owner','owner@example.com'),('executor','executor@example.com');
 CREATE TABLE counterparties(id TEXT,name TEXT);INSERT INTO counterparties VALUES('c','Client');
 CREATE TABLE crm_deals(id TEXT,title TEXT,deadline TEXT,responsible_id TEXT,executor_id TEXT,client_id TEXT,stage TEXT,deleted_at TEXT);
 INSERT INTO crm_deals VALUES('d','Deal','2026-11-30','owner','executor','c','work',NULL);`);
 initCrmMail(db);const messages=[];const send=async m=>messages.push(m);const at=new Date('2026-11-25T07:00:00Z');
 await processCrmMail(db,{at,send,configured:false});assert.equal(messages.length,0);
 await processCrmMail(db,{at:new Date('2026-11-25T03:00:00Z'),send,configured:true});assert.equal(messages.length,0);
 await processCrmMail(db,{at,send,configured:true});assert.equal(messages.length,1);assert.equal(messages[0].to,'owner@example.com');assert.match(messages[0].body,/#\/crm\?deal=d/);
 initCrmMail(db);await processCrmMail(db,{at,send,configured:true});assert.equal(messages.length,1);
 db.exec("UPDATE crm_deals SET deadline='2026-11-27'");
 await processCrmMail(db,{at,send:async()=>{throw Error('offline')},configured:true});
 assert.equal(db.prepare("SELECT count(*) n FROM crm_mail_deliveries WHERE status='failed'").get().n,1);
 await processCrmMail(db,{at,send,configured:true});assert.equal(messages.length,1);
 await processCrmMail(db,{at:new Date(at.getTime()+3600000),send,configured:true});assert.equal(messages.length,2);
 db.exec("UPDATE crm_deals SET stage='act_ready',deadline='2026-11-26'");
 await processCrmMail(db,{at,send,configured:true});assert.equal(messages.length,2);db.close();
});
